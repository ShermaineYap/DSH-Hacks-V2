// End-to-end checks against the deployed site with a phone viewport.
const { createRequire } = require("node:module");
let pw; try { pw = require("playwright"); } catch { pw = require(process.env.PLAYWRIGHT_PATH || "/opt/npm-tools/node_modules/playwright"); }
const { chromium, devices } = pw;
const base = process.argv[2] || "https://dsh-hacks-v2-jade.vercel.app";
const results = [];
const check = (name, ok, extra = "") => { results.push({ name, ok }); console.log(`${ok ? "PASS" : "FAIL"} ${name} ${extra}`); };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices["iPhone 13"] });
  const p = await ctx.newPage();
  const errors = []; p.on("pageerror", (e) => errors.push(e.message));
  await p.goto(base + "/"); await p.waitForSelector("h1");
  check("demo opens on day 5 with hospital verdict", (await p.textContent("h1")).includes("hospital emergency department"));
  await p.locator('[data-day="3"]').click(); await p.waitForTimeout(300);
  check("day 3 → home", (await p.textContent("h1")).includes("resting at home"));
  check("day 3 shows tomorrow's blood test", (await p.textContent("main")).includes("Tomorrow is day 4"));
  await p.locator('[data-day="1"]').click(); await p.waitForTimeout(300);
  check("day 1 → home, no daily-review reason", (await p.textContent("h1")).includes("resting at home"));
  await p.getByRole("button", { name: "BM", exact: true }).click(); await p.waitForTimeout(300);
  check("BM toggle", (await p.textContent("h1")).includes("berehat di rumah"));
  await p.getByRole("button", { name: "EN", exact: true }).click();
  await p.locator('[data-day="4"]').click(); await p.waitForTimeout(300);
  await p.fill("textarea", "perut sakit sangat, gusi berdarah sikit pagi tadi");
  await p.getByRole("button", { name: "Find signs in my message" }).click();
  await p.waitForSelector("text=Found in your message", { timeout: 40000 });
  const found = await p.locator('[role="status"]').textContent();
  check("message → stomach pain + bleeding", found.includes("Stomach pain") && found.includes("bleeding"), found.slice(-60));
  await p.getByRole("button", { name: "Save today's check-in" }).click(); await p.waitForTimeout(400);
  check("saving signs escalates day 4 to hospital", (await p.textContent("h1")).includes("hospital emergency department"));
  await p.getByRole("button", { name: "Try a sample slip" }).click();
  await p.waitForSelector("text=Check each number", { timeout: 60000 });
  const plt = await p.locator('input[inputmode="decimal"]').nth(1).inputValue();
  check("sample slip read (platelets 71)", plt === "71", `plt=${plt}`);
  check("slip shows printed text for confirmation", (await p.textContent("main")).includes("On slip"));
  await p.goto(base + "/evidence"); await p.waitForSelector("h1");
  check("evidence page", (await p.textContent("h1")).includes("How well Fasa works"));
  await p.goto(base + "/"); await p.getByRole("button", { name: "Start my own record" }).click();
  await p.waitForSelector("text=Set up your record");
  await p.locator('input[inputmode="numeric"]').fill("30");
  await p.getByRole("button", { name: "Start", exact: true }).click(); await p.waitForTimeout(400);
  check("own record starts at day 2 with a verdict", (await p.textContent("main")).includes("day 2 of your illness"));
  await p.reload(); await p.waitForTimeout(500);
  check("own record survives reload", (await p.textContent("main")).includes("day 2 of your illness"));
  check("no page errors", errors.length === 0, errors.join(" | "));
  await b.close();
  const failed = results.filter((r) => !r.ok).length;
  console.log(`${results.length - failed}/${results.length} passed`);
  process.exit(failed ? 1 : 0);
})();
